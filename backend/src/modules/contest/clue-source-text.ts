  en: "Find the English word immediately after the phrase shown in the hint.",
  de: "Finde das deutsche Wort unmittelbar nach der im Hinweis gezeigten Wortgruppe.",
  es: "Encuentra la palabra en español que aparece inmediatamente después de la frase indicada.",
  fr: "Trouvez le mot français qui suit immédiatement l’expression affichée dans l’indice.",
  ar: "اعثر على الكلمة العربية التي تأتي مباشرة بعد العبارة الظاهرة في التلميح.",
  tr: "İpucunda gösterilen ifadenin hemen ardından gelen Türkçe kelimeyi bulun.",
  pt: "Encontre a palavra em português que aparece imediatamente após a frase indicada.",
