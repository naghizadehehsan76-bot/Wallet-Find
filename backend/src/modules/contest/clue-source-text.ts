export function generatedClueInstruction(language: ChallengeLanguage): string {
  const instruction = CLUE_INSTRUCTIONS[language];
  // This marker is not rendered while a valid hint anchor exists. It lets the
  // scheduler retire rounds generated by the older, unreliable HTML scraper.
  return `${CLUE_GENERATOR_VERSION} ${instruction}`;
}

/**
 * Convert extracted source text into readable paragraphs. Single line breaks
 * inside a paragraph (for example, Project Gutenberg line wrapping) become
 * spaces, but paragraph boundaries are retained so hints cannot bridge them.
 */
export function normalizeSourceText(value: string): string {
  return value
    .replace(/\u00a0/g, " ")
    .replace(/\r/g, "")
    .replace(/\uFEFF/g, "")
    .split(/\n[ \t]*\n+/)
    .map((paragraph) =>
      paragraph
        .replace(/[ \t]*\n[ \t]*/g, " ")
        .replace(/[ \t]+/g, " ")
        .trim(),
    )
    .filter(Boolean)
    .join("\n\n");
}

function decodeHtmlEntities(value: string): string {
  const named: Record<string, string> = {
    amp: "&",
    lt: "<",
    gt: ">",
    quot: '"',
    apos: "'",
    nbsp: " ",
    ensp: " ",
    emsp: " ",
    thinsp: " ",
    ndash: "–",
    mdash: "—",
    hellip: "…",
    lsquo: "‘",
    rsquo: "’",
    ldquo: "“",
    rdquo: "”",
    zwnj: "\u200c",
    lrm: "\u200e",
    rlm: "\u200f",
  };

  return value.replace(/&(#x[\da-f]+|#\d+|[a-z][\da-z]+);/gi, (entity, reference: string) => {
    if (reference.startsWith("#x") || reference.startsWith("#X")) {
      const codePoint = Number.parseInt(reference.slice(2), 16);
      return Number.isFinite(codePoint) && codePoint >= 0 && codePoint <= 0x10ffff
        ? String.fromCodePoint(codePoint)
        : entity;
    }
    if (reference.startsWith("#")) {
      const codePoint = Number.parseInt(reference.slice(1), 10);
      return Number.isFinite(codePoint) && codePoint >= 0 && codePoint <= 0x10ffff
        ? String.fromCodePoint(codePoint)
        : entity;
    }
    return named[reference.toLowerCase()] ?? entity;
  });
}

/**
 * Extract visible text from HTML, including rendered MediaWiki parser output.
 * Block-level boundaries are preserved so anchors cannot bridge paragraphs.
 */
export function extractVisibleTextFromHtml(html: string): string {
  const blockTags = "address|article|blockquote|dd|div|dl|dt|figcaption|figure|h[1-6]|li|main|ol|p|pre|section|table|tbody|td|th|tr|ul";
  const visibleText = html
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/<(script|style|nav|header|footer|aside|form|button|noscript|template|iframe|svg|select|textarea)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, " ")
    .replace(/<br\b[^>]*>/gi, "\n")
    .replace(new RegExp(`<\\/(?:${blockTags})\\s*>`, "gi"), "\n\n")
    .replace(new RegExp(`<(?:${blockTags})\\b[^>]*>`, "gi"), "\n\n")
    .replace(/<[^>]*>/g, "");

  return normalizeSourceText(decodeHtmlEntities(visibleText));
}

function normalizeForHintComparison(value: string): string {
  return value
    .normalize("NFKC")
    .replace(/[\u200b-\u200f\u202a-\u202e\u2060\ufeff]/g, "")
    .replace(/[\u064b-\u065f\u0670\u06d6-\u06ed]/g, "")
    .replace(/\u0640/g, "")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/\u00a0/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLocaleLowerCase();
}

const LANGUAGE_LOCALES: Record<ChallengeLanguage, string> = {
  fa: "fa-IR",
  en: "en",
  de: "de",
  es: "es",
  fr: "fr",
  ar: "ar",
  tr: "tr",
  pt: "pt",
  ru: "ru",
  "zh-CN": "zh-CN",
};

function normalizeSourceWord(raw: string, language: ChallengeLanguage): string {
  const normalized = raw.normalize("NFKC")
    .replace(/[\u064b-\u065f\u0670\u06d6-\u06ed]/g, "")
    .replace(/\u0640/g, "")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک");
  return normalized.toLocaleLowerCase(LANGUAGE_LOCALES[language]);
}

export function getSourceWordMatches(
  text: string,
  language: ChallengeLanguage = "en",
): SourceWordMatch[] {
  if (language === "zh-CN") {
    const segmenter = new Intl.Segmenter("zh-CN", { granularity: "word" });
    return Array.from(segmenter.segment(text))
      .filter((segment) => segment.isWordLike && /\p{Script=Han}/u.test(segment.segment))
      .map((segment) => ({
        word: normalizeSourceWord(segment.segment, language),
        raw: segment.segment,
        index: segment.index,
      }))
      .filter((match) => match.word.length > 0);
  }

  const pattern = language === "fa"
    ? /[\u0621-\u063a\u0640-\u065f\u0670-\u06d3\u067e\u0686\u0698\u06a9\u06af\u06be\u06cc\u200c]{3,24}/gu
    : language === "ar"
      ? /[\p{Script=Arabic}]{3,24}/gu
      : language === "ru"
        ? /[\p{Script=Cyrillic}]{4,24}/gu
        : /[\p{Script=Latin}]{4,24}/gu;

  return Array.from(text.matchAll(pattern)).map((match) => {
    const raw = match[0];
    return {
      word: normalizeSourceWord(raw, language),
      raw,
      index: match.index ?? 0,
    };
  });
}

/**
 * Return true only for a literal phrase that can safely be searched on the
 * rendered source page. A clue containing template syntax or maintenance
 * metadata is rejected rather than shown to participants.
 */
export function isSearchableClueAnchor(anchor: string): boolean {
  const trimmed = anchor.trim();
  return (
    trimmed.length >= 25 &&
    trimmed.length <= 160 &&
    !/[\r\n]/.test(trimmed) &&
    !/\{\{|\}\}|<[^>]*>|نگهداری\s+یادکرد|(?:cite\s+web|یادکرد\s+وب)\s*:\s*|یادکرد\s*:\s*(?:تاریخ|سال|ماه|زبان|عنوان)/iu.test(trimmed)
  );
}

/**
 * Match source assignments without treating two different pinned Wikipedia
 * revisions as the same page. Unpinned assignments may be resolved and pinned
 * to the current revision when the challenge is generated.
 */
export function sourceUrlMatchesAssignment(
  actualUrl: string | null | undefined,
  assignedUrl: string,
): boolean {
  if (!actualUrl) return false;
  try {
    const actual = new URL(actualUrl);
    const assigned = new URL(assignedUrl);
    if (actual.origin !== assigned.origin) return false;

    if (actual.hostname === "en.wikipedia.org" || actual.hostname === "fa.wikipedia.org") {
      if (actual.pathname !== assigned.pathname) return false;
      const assignedRevision = assigned.searchParams.get("oldid");
      return !assignedRevision || actual.searchParams.get("oldid") === assignedRevision;
    }
    return actual.toString() === assigned.toString();
  } catch {
    return actualUrl === assignedUrl;
  }
}

function countNormalizedOccurrences(source: string, phrase: string): number {
  if (!phrase) return 0;
  let count = 0;
  let from = 0;
  while (from <= source.length - phrase.length) {
    const index = source.indexOf(phrase, from);
    if (index < 0) break;
    count += 1;
    from = index + 1;
  }
  return count;
}

/**
 * Selects a unique phrase immediately before a target word. Candidates are
 * copied verbatim from one paragraph and never cross sentence boundaries.
 */
export function findUniqueAnchorBeforeTarget(
  sourceText: string,
  matches: readonly SourceWordMatch[],
  targetIndex: number,
): string | null {
  const target = matches[targetIndex];
  if (!target) return null;

  const comparisonSource = normalizeForHintComparison(sourceText);
  for (let wordsBefore = 5; wordsBefore <= 10; wordsBefore += 1) {
    const firstWord = matches[targetIndex - wordsBefore];
    if (!firstWord) continue;

    const rawAnchor = sourceText.slice(firstWord.index, target.index);
    if (!rawAnchor || /[\r\n]/.test(rawAnchor)) continue;
    // Treat punctuation as a sentence boundary even when markup follows it
    // with no intervening whitespace (a common parser artifact on Wikipedia).
    if (/[.!?؟؛۔。！？；][)\]"'»’”\]]*(?:\s|[{<]|$)/u.test(rawAnchor)) continue;

    const anchor = rawAnchor.replace(/\s+/g, " ").trim();
    if (!isSearchableClueAnchor(anchor)) continue;

    const comparisonAnchor = normalizeForHintComparison(anchor);
    if (countNormalizedOccurrences(comparisonSource, comparisonAnchor) !== 1) continue;

    // The answer must really be the next source token after the copied phrase.
    const tail = sourceText.slice(target.index);
    if (!tail.startsWith(target.raw)) continue;

    return anchor;
  }
  return null;
}
